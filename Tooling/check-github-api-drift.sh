#!/bin/sh
# The drift guard CI runs: regenerates the GitHub client and fails if
# Specs/github or Sources/GitHubAPI/Generated then differ from the commit,
# new files included. Catches hand edits to the generated code, and pin,
# fix, or generator changes committed without regenerating.
#
# Usage: Tooling/check-github-api-drift.sh   (needs a clean checkout of those paths)
set -eu

root=$(cd "$(dirname "$0")/.." && pwd)
"$root/Tooling/generate-github-api.sh"

cd "$root"
drift=$(git status --porcelain -- Specs/github Sources/GitHubAPI/Generated)
if [ -n "$drift" ]; then
    echo "$drift"
    git --no-pager diff --stat -- Specs/github Sources/GitHubAPI/Generated
    echo "::error::The committed GitHub client differs from what Tooling/generate-github-api.sh generates. Run it and commit the result; never edit Sources/GitHubAPI/Generated by hand."
    exit 1
fi
echo "The committed GitHub client matches the pipeline's output."
